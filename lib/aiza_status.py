# Only in the Email box, where the digest's watch tool is (2026-11-20, the
# user: 「セッションが新着まとめに起こすことを依頼できる仕組みがほしい」).
WATCH_TOOL = "~/digest/watch.mjs"
WATCH_RULE = ('\nメールやチャットの到着を待って寝かせるときは、起きる条件を見張りとして置いてください(置かないと日時でしか起きません):\n'
              "  node ~/digest/watch.mjs add --query 'from:相手 注文番号など' --task '起きたらすること'\n"
              '  (--thread <threadId>・--keyword <語> [--from <差出人>]・--until <日付> も使えます。確かめる・外す: watch.mjs list / rm <id>)')


def rule():
    import os
    return (RULE + (TREE_RULE if os.environ.get("AIZA_TREE") else "")
            + (WATCH_RULE if os.path.exists(os.path.expanduser(WATCH_TOOL)) else ""))
